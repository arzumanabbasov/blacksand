"""Generate SQLite's final table/index definitions from the PostgreSQL schema.

PostgreSQL's historical ALTER/DO migrations are folded into fresh SQLite tables.
Runtime SQLite migrations are versioned separately; this is a source generator.
"""
import re
import sqlite3
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'db/schema.sql').read_text(encoding='utf-8-sig')
for extra in ('commands.go', 'llm_usage.go'):
    code = (ROOT / 'db' / extra).read_text(encoding='utf-8-sig')
    for block in re.findall(r'`([^`]+)`', code, re.S):
        if 'CREATE TABLE IF NOT EXISTS llm_records' in block or 'CREATE TABLE IF NOT EXISTS llm_usage' in block:
            source += '\n' + block
source = re.sub(r'--[^\n]*', '', source)

def split_columns(body):
    parts, start, depth, quoted, i = [], 0, 0, False, 0
    while i < len(body):
        c = body[i]
        if c == "'":
            if quoted and i + 1 < len(body) and body[i + 1] == "'":
                i += 2
                continue
            quoted = not quoted
        elif not quoted:
            if c == '(': depth += 1
            elif c == ')': depth -= 1
            elif c == ',' and depth == 0:
                parts.append(body[start:i].strip())
                start = i + 1
        i += 1
    parts.append(body[start:].strip())
    return parts

tables = {}
for match in re.finditer(r'CREATE TABLE IF NOT EXISTS (\w+)\s*\(', source, re.I):
    start = match.end()
    depth, quoted, end = 1, False, start
    while depth:
        c = source[end]
        if c == "'":
            if quoted and source[end + 1] == "'":
                end += 2
                continue
            quoted = not quoted
        elif not quoted:
            if c == '(': depth += 1
            elif c == ')': depth -= 1
        end += 1
    tables[match[1]] = split_columns(source[start:end - 1])

for match in re.finditer(r'ALTER TABLE (\w+) ADD COLUMN (?:IF NOT EXISTS )?(\w+)\s+([^;]+);', source, re.I):
    table, name, definition = match.groups()
    if table not in tables: raise RuntimeError('Unknown table ' + table)
    if not any(re.match(r'\s*' + re.escape(name) + r'\s', col) for col in tables[table]):
        tables[table].append(name + ' ' + definition.strip())

# Fold the latest named CHECK definitions into each final table.
for match in re.finditer(r'ALTER TABLE (\w+) ADD\s+CONSTRAINT (\w+)\s+(CHECK\s*\([^;]+);', source, re.I):
    table, name, definition = match.groups()
    if table not in tables: continue
    columns = tables[table]
    columns[:] = [col for col in columns if not re.match(r'CONSTRAINT\s+' + re.escape(name) + r'\b', col, re.I)]
    # Inline unnamed original CHECKs on columns need the expanded final check.
    if name == 'company_scope_kind_check':
        columns[:] = [re.sub(r"CHECK\s*\(kind\s+IN\s*\([^)]*\)\)", '', col) if col.startswith('kind ') else col for col in columns]
    if name == 'llm_profiles_format_check':
        columns[:] = [re.sub(r"CHECK\s*\(format\s+IN\s*\([^)]*\)\)", '', col) if col.startswith('format ') else col for col in columns]
    columns.append('CONSTRAINT ' + name + ' ' + definition.strip())

def translate(statement):
    literals = []
    def mask(match):
        literals.append(match[0])
        return f'__SQLITE_LITERAL_{len(literals)-1}__'
    statement = re.sub(r"'(?:''|[^'])*'", mask, statement)
    statement = re.sub(r'\b(?:BIGSERIAL|SERIAL)\s+PRIMARY KEY', 'INTEGER PRIMARY KEY AUTOINCREMENT', statement, flags=re.I)
    statement = re.sub(r'\b(?:BIGINT|TEXT|JSONB)\[\]', 'TEXT', statement, flags=re.I)
    statement = re.sub(r'\bJSONB\b|\bCIDR\b|\bINET\b|\bBYTEA\b', lambda m: 'BLOB' if m[0].upper() == 'BYTEA' else 'TEXT', statement, flags=re.I)
    statement = re.sub(r'\bTIMESTAMPTZ\b', 'TIMESTAMP', statement, flags=re.I)
    statement = re.sub(r'\bDEFAULT now\(\)', "DEFAULT (strftime('%Y-%m-%d %H:%M:%f+00:00','now'))", statement, flags=re.I)
    statement = re.sub(r"::(?:text|jsonb|json|bigint|int|integer|boolean|cidr)(?:\[\])?", '', statement, flags=re.I)
    statement = statement.replace('jsonb_typeof(', 'json_type(').replace('jsonb_array_length(', 'json_array_length(')
    statement = re.sub(r'(\w+)\s*~\s*(__SQLITE_LITERAL_\d+__)', r'sw_regex(\1,\2)', statement)
    statement = re.sub(r'\s+INCLUDE\s*\([^)]*\)', '', statement, flags=re.I)
    for index, value in enumerate(literals):
        statement = statement.replace(f'__SQLITE_LITERAL_{index}__', value)
    return statement

output = ['-- Generated by tools/generate_sqlite_schema.py. SQLite schema version 1.']
metadata = {}
for table, columns in tables.items():
    columns = [column for column in columns if not re.match(r'(?:CONSTRAINT|PRIMARY|UNIQUE|CHECK|FOREIGN)\b', column, re.I)] + [column for column in columns if re.match(r'(?:CONSTRAINT|PRIMARY|UNIQUE|CHECK|FOREIGN)\b', column, re.I)]
    converted = []
    metadata[table] = []
    for column in columns:
        is_array = bool(re.search(r'\b\w+\[\]', column))
        is_json = bool(re.search(r'\bJSONB\b', column)) or is_array
        column_name = column.split()[0]
        if not re.match(r'(?:CONSTRAINT|PRIMARY|UNIQUE|CHECK|FOREIGN)\b', column, re.I):
            metadata[table].append(dict(name=column_name, json=is_json, boolean=bool(re.search(r'\bBOOLEAN\b',column)), binary=bool(re.search(r'\bBYTEA\b',column))))
        if table == 'side_question_requests' and column_name == 'id':
            column = column.replace('PRIMARY KEY', 'UNIQUE')
        if table == 'side_question_requests' and column_name == 'ordinal':
            column = 'ordinal INTEGER PRIMARY KEY AUTOINCREMENT'
        column = translate(column)
        if is_array: column = column.replace("DEFAULT '{}'", "DEFAULT '[]'")
        if is_json: column += f' CHECK ({column_name} IS NULL OR json_valid({column_name}))'
        converted.append(column)
    output.append(f'CREATE TABLE IF NOT EXISTS {table} (\n    ' + ',\n    '.join(converted) + '\n);')

for match in re.finditer(r'CREATE (?:UNIQUE )?INDEX IF NOT EXISTS[^;]+;', source, re.I):
    statement = match[0]
    if re.search(r'\bUSING (?:GIN|GIST)\b', statement, re.I): continue
    output.append(translate(statement))

for table, columns in tables.items():
    if any(re.match(r'updated_at\s', col) for col in columns):
        output.append(f"CREATE TRIGGER IF NOT EXISTS sw_{table}_updated AFTER UPDATE ON {table}\nWHEN NEW.updated_at = OLD.updated_at BEGIN\nUPDATE {table} SET updated_at=strftime('%Y-%m-%d %H:%M:%f+00:00','now') WHERE rowid=NEW.rowid; END;")

output.append("CREATE TRIGGER IF NOT EXISTS sw_stop_conversation_retest BEFORE DELETE ON conversations BEGIN UPDATE finding_retests SET status='stopped', error='Retest conversation deleted', finished_at=strftime('%Y-%m-%d %H:%M:%f+00:00','now') WHERE conversation_id=OLD.id AND status IN ('pending','running'); END;")
schema = '\n\n'.join(output) + '\n'
validation = sqlite3.connect(':memory:')
validation.create_function('sw_regex', 2, lambda value, pattern: bool(re.search(pattern, value)), deterministic=True)
validation.executescript(schema)
validation.close()
(ROOT / 'db/schema_sqlite.sql').write_text(schema, encoding='utf-8')
(ROOT / 'db/schema_sqlite_columns.json').write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
print(f'Generated {len(tables)} SQLite tables')
